export function extraSeedJobs(): NormalizedJob[] {
  return EXTRA.map((e, i) => ({
    source: (["ARBEITNOW", "REMOTIVE", "ADZUNA"] as const)[i % 3],
    externalId: `seed-${i + 1}`,
    title: e.title,
    company: e.company,
    location: e.location,
    remote: e.remote,
    description: `${e.about} You will work with ${e.stack}. We offer a collaborative team, flexible hours and room to grow. Remote work: ${e.remote ? "yes" : "hybrid in the office"}.`,
    url: `https://example.com/jobs/seed-${i + 1}`,
    salaryMin: e.salary?.[0] ?? null,
    salaryMax: e.salary?.[1] ?? null,
    currency: e.salary ? "EUR" : null,
    postedAt: null,
  }));
}
